"""Writes src/zones.js: which country each time zone is in.

Reads the time zone database that ships with the system (zone.tab, plus the old names that
browsers still report, such as Asia/Calcutta) and maps every zone name to an ISO country code.
Run it again when the database changes:  python3 tools/make-zones.py [/usr/share/zoneinfo]
"""
import os, sys, json, filecmp

ZI = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/zoneinfo'
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'zones.js')

zones = {}
for line in open(os.path.join(ZI, 'zone.tab')):
    if line.startswith('#') or not line.strip():
        continue
    cc, _, name = line.split('\t')[:3]
    zones[name.strip()] = cc

# links: "L Target Alias" in tzdata.zi
for line in open(os.path.join(ZI, 'tzdata.zi')):
    if line.startswith('L '):
        _, target, alias = line.split()
        if alias not in zones and target in zones:
            zones[alias] = zones[target]

# names left over (old ones the database keeps as copies): same file as a zone of exactly one country
by_country = {}
for name, cc in zones.items():
    by_country.setdefault(cc, []).append(name)
for root, _, files in os.walk(ZI):
    for f in files:
        path = os.path.join(root, f)
        name = os.path.relpath(path, ZI)
        if name in zones or '/' not in name or name.startswith(('posix/', 'right/', 'Etc/', 'SystemV/')):
            continue
        matches = {cc for z, cc in zones.items() if os.path.exists(os.path.join(ZI, z)) and filecmp.cmp(path, os.path.join(ZI, z), shallow=False)}
        if len(matches) == 1:
            zones[name] = matches.pop()

# old names some browsers still report, in case the system database dropped them
for alias, cc in {'Asia/Calcutta': 'IN', 'Asia/Saigon': 'VN', 'Asia/Katmandu': 'NP', 'Asia/Rangoon': 'MM',
                  'Europe/Kiev': 'UA', 'Atlantic/Faeroe': 'FO', 'America/Buenos_Aires': 'AR',
                  'Asia/Istanbul': 'TR', 'Pacific/Truk': 'FM', 'Pacific/Ponape': 'FM'}.items():
    zones.setdefault(alias, cc)

body = json.dumps(dict(sorted(zones.items())), separators=(',', ':'))
with open(OUT, 'w') as out:
    out.write('/* Price Lens: the country each time zone is in. Generated by tools/make-zones.py from the\n'
              ' * time zone database; do not edit by hand. */\n')
    out.write(f'export const ZONE_COUNTRY = {body};\n')
print(len(zones), 'zones ->', OUT)
